  def icon(name, options = {})
    tag.svg(xmlns: "http://www.w3.org/2000/svg", fill: "none", viewBox: "0 0 24 24", "stroke-width": options.fetch(:stroke, 1.75),
            stroke: "currentColor", class: options.fetch(:class, "size-5"), aria: { hidden: true }) do
      tag.path("stroke-linecap": "round", "stroke-linejoin": "round", d: ICONS.fetch(name))
    end
  end

  # Inisial untuk avatar, contoh "Budi Santoso" → "BS".
  def initials(name)
    name.to_s.split.first(2).map { |word| word[0] }.join.upcase.presence || "?"
  end

  def nav_active?(path)
    path == root_path ? current_page?(root_path) : request.path.start_with?(path)
  end

  # Menu samping (laptop) atau menu bawah (HP).
  def nav_link(label, path, icon_name, variant: :side)
    active = nav_active?(path)

    if variant == :bottom
      classes = active ? "text-brand-600" : "text-muted hover:text-ink"
      link_to path, class: "bottom-nav-item #{classes}", aria: { current: (active ? "page" : nil) } do
        icon(icon_name, class: "size-6", stroke: (active ? 2 : 1.75)) + tag.span(label)
      end
    else
      classes = active ? "bg-brand-600 text-white shadow-soft" : "text-muted hover:bg-canvas hover:text-ink"
      link_to path, class: "nav-item #{classes}", aria: { current: (active ? "page" : nil) } do
        icon(icon_name) + tag.span(label)
      end
    end
  end

  def rupiah(amount)
    number_to_currency(amount)
  end

  def phone_display(number)
    PhoneNumber.display(number)
  end

  def invoice_status_badge(invoice)
    label, classes =
      if invoice.paid?
        [ "Lunas", "bg-success-50 text-success-700" ]
      elsif invoice.overdue?
        [ "Telat", "bg-danger-50 text-danger-700" ]
      else
        [ "Belum bayar", "bg-warning-50 text-warning-700" ]
      end

    tag.span label, class: "badge #{classes}"
  end

  def paid_via_label(paid_via)
    { "cash" => "Tunai", "qris" => "QRIS", "bank_transfer" => "Virtual Account" }.fetch(paid_via.to_s, "-")
  end

  def whatsapp_url_for(invoice)
    InvoiceMessage.new(invoice, link: public_invoice_url(invoice.public_token)).whatsapp_url
  end
